"""
AI-Generated Dataset Test Runner.
Executes parameterized test scenarios generated by AI dataset matrix (positive, negative, boundary, exception).
"""

import re
import pytest
from playwright.sync_api import Page, expect
from pages.login_page import LoginPage
from pages.checkout_page import CheckoutPage
from pages.dashboard_page import DashboardPage
from utils.data_loader import load_ai_dataset


# Load all AI dataset test cases
dataset_cases = load_ai_dataset()


@pytest.mark.regression
@pytest.mark.ai_generated
@pytest.mark.parametrize("test_case", dataset_cases, ids=[tc["id"] for tc in dataset_cases])
def test_ai_generated_scenario(page: Page, server_url: str, test_case: dict):
    """
    Parameterized test executor driving AI dataset variations against application POM classes.
    
    Categories handled:
        - positive: Valid inputs expected to succeed.
        - negative: Invalid inputs expecting error banners.
        - boundary: Edge case inputs (empty fields, 100% discount codes).
        - exception: Injection vectors and unusual payload inputs.
    """
    feature = test_case.get("feature")
    category = test_case.get("category")
    inputs = test_case.get("input", {})
    expected = test_case.get("expected", {})

    if feature == "login":
        login_page = LoginPage(page, base_url=server_url)
        dashboard_page = DashboardPage(page)

        login_page.navigate_to_login()
        login_page.login(inputs.get("username", ""), inputs.get("password", ""))

        if expected.get("should_succeed"):
            expect(page).to_have_url(re.compile(rf".*{re.escape(expected.get('redirect_url_contains'))}.*"))
            assert dashboard_page.get_current_username() == expected.get("welcome_user")
        else:
            assert login_page.is_error_visible()
            assert login_page.get_error_message() == expected.get("error_message")

    elif feature == "checkout":
        checkout_page = CheckoutPage(page)
        checkout_page.navigate_to_checkout(server_url)
        checkout_page.apply_promo_code(inputs.get("promo_code", ""))

        if expected.get("should_succeed"):
            assert checkout_page.get_discount_text() == expected.get("discount_amount")
            assert checkout_page.get_total_text() == expected.get("total_amount")
        else:
            assert checkout_page.get_checkout_error_message() == expected.get("error_message")

    elif feature == "search":
        login_page = LoginPage(page, base_url=server_url)
        dashboard_page = DashboardPage(page)

        login_page.navigate_to_login()
        login_page.login("admin", "admin123")
        dashboard_page.search_product(inputs.get("query", ""))

        assert expected.get("escaped_output") in dashboard_page.get_search_results_text()
